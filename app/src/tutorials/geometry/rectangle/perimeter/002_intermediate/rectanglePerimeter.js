function rectanglePerimeter(length, width)
{
    // Convert both inputs to numbers
    let numLength = parseFloat(length);
    
    let numWidth = parseFloat(width);
    
    let perimeterResult = 2 * (numLength + numWidth);
    
    return perimeterResult;
}

